    ConfirmSignOutAction, KeepSignedIn, LocalTitle, LocalBody, Library, Preferences,
    Avatar, NeutralAvatar, AuthAvailableLater,
}

/** Exhaustive vi/en copy. No capability or current account is inferred from the locale. */
fun ShellStrings.account(copy: AccountCopy): String = if (vietnamese) vietnameseAccount(copy) else englishAccount(copy)

